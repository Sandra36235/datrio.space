// Rules for «¿Qué gráfico uso?»: goal → (time? many categories?) → ids in order of preference.
export function recommend(goal,time,many){
 const r={
  comparar:time?['lineas','cinta','columnas']:many?['barras','tabla','treemap']:['columnas','barras'],
  tendencia:['lineas','area','combinado'],
  composicion:time?['apiladas','apiladas100','area']:many?['treemap','barras','apiladas100']:['anillo','circular','apiladas100'],
  cambio:['cascada','descomposicion'],
  relacion:['dispersion','influenciadores'],
  ubicacion:['mapaazure','matriz'],
  numero:['tarjeta','kpi','medidor'],
  proceso:['embudo','cascada'],
  detalle:many?['matriz','tabla']:['tabla','matriz'],
  filtrar:many?['entrada','lista','segmentacion']:['botones','segmentacion'],
  explicar:['descomposicion','influenciadores','narrativa']
 }[goal]||[];
 return r.map(id=>VIZ.find(v=>v.id===id)).filter(Boolean);
}
